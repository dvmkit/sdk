import {
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  renameSync,
  unlinkSync,
  writeFileSync,
} from "fs";

import { BUILDER_CONFIG_DIR, BUILDER_FILE } from "../defaults";
import { DvmError } from "./errors";
import { backupSecretFile } from "./secret-backup";

/**
 * Per-DVM state the builder CLI persists locally to recover BIP-32 derivations
 * One row per immutable DVM ID. The mnemonic lives at
 * `~/.dvmkit/recovery.mnemonic` (written by `dvmctl keygen`).
 */
export interface BuilderDvmEntry {
  /**
   * The DVM's slug. Informational for platform DVMs, and the lookup handle
   * for self-hosted DVMs, which do not have a platform selection surface.
   */
  handle: string;
  /**
   * The DVM's stable identifier — the platform's `dvms.id` UUID for cloud
   * deploys, or a locally-generated UUIDv4 for `dvmctl init --self-hosted`.
   * Hashed into the BIP-32 path at `m/1789'/0'/hashed(canonical_dvm_id)'/N'`.
   */
  canonical_dvm_id: string;
  /**
   * Newest published rotation index. Initial deploy persists `0`. `dvmctl
   * rotate` increments this; `dvmctl melt-pending` walks
   * `0..current_rotation_index` to find the privkey matching each proof.
   */
  current_rotation_index: number;
  /** True when the canonical_id was generated locally by `dvmctl init`. */
  self_hosted?: boolean;
  /**
   * Default Lightning address that `dvmctl melt-pending` melts to when
   * `--payout` is omitted. Persisted via `dvmctl set-payout`;
   * the CLI does not validate format on read — that happens at write time
   * and at melt time via the LNURL pre-flight.
   */
  payout_ln_address?: string;
  /** ISO-8601 of the last write (deploy, rotate, set-payout). */
  updated_at: string;
}

export interface BuilderStore {
  version: 2;
  /**
   * Builder identity secp256k1 x-only pubkey (32 bytes hex). Builder-wide:
   * one identity key signs deploy attestations for every DVM the operator
   * publishes. Generated by `dvmctl identity create`; the matching
   * secret lives in {@link BUILDER_KEY_FILE}. Absent until the operator runs
   * the create command — `dvmctl deploy` errors with `identity_required` in
   * that state.
   */
  identity_pubkey?: string;
  /** Per-DVM state, keyed by immutable `canonical_dvm_id`. */
  dvms: Record<string, BuilderDvmEntry>;
}

const CURRENT_VERSION = 2;

/**
 * Load the builder store from disk, returning an empty store when the file
 * does not exist. Throws when the file exists but is unparseable or carries
 * an unknown `version` — refuses to silently overwrite operator data. v1
 * keyed entries by slug; it is migrated in memory to v2, which keys them by
 * immutable canonical IDs. The next ordinary write persists the v2 shape.
 */
export function loadBuilderStore(): BuilderStore {
  if (!existsSync(BUILDER_FILE)) {
    return { version: CURRENT_VERSION, dvms: {} };
  }
  const raw = readFileSync(BUILDER_FILE, "utf-8");
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch (err) {
    throw new Error(
      `${BUILDER_FILE} is not valid JSON: ${err instanceof Error ? err.message : String(err)}`,
      { cause: err }
    );
  }
  if (typeof parsed !== "object" || parsed === null) {
    throw new Error(`${BUILDER_FILE} is not a JSON object`);
  }
  const values = parsed as Record<string, unknown>;
  const version = values.version;
  if (version === 1) {
    return migrateV1Store(parsed as Record<string, unknown>);
  }
  if (version !== CURRENT_VERSION) {
    throw new Error(
      `${BUILDER_FILE} has unknown version ${String(version)} (expected ${CURRENT_VERSION})`
    );
  }
  if (typeof values.dvms !== "object" || values.dvms === null) {
    throw new Error(`${BUILDER_FILE} is missing the dvms object`);
  }
  return {
    version: CURRENT_VERSION,
    ...(typeof values.identity_pubkey === "string"
      ? { identity_pubkey: values.identity_pubkey }
      : {}),
    dvms: values.dvms as Record<string, BuilderDvmEntry>,
  };
}

/**
 * Read the builder identity pubkey from `~/.dvmkit/builder.json`.
 * Returns `null` when the file is absent or the field is unset — callers
 * (e.g. `dvmctl deploy`) treat that as the "no identity yet" state and
 * surface an `identity_required` error.
 */
export function loadIdentityPubkey(): string | null {
  return loadBuilderStore().identity_pubkey ?? null;
}

/**
 * Write the builder identity pubkey to `~/.dvmkit/builder.json`.
 * Preserves all existing per-DVM entries. Mode 0600 on the file. Use the
 * higher-level `writeIdentity` in `lib/builder-identity.ts` when also writing
 * the secret.
 */
export function setIdentityPubkey(pubkey: string): void {
  mkdirSync(BUILDER_CONFIG_DIR, { recursive: true, mode: 0o700 });
  const store = loadBuilderStore();
  store.identity_pubkey = pubkey;
  writeBuilderStore(store);
}

/** Read a single DVM entry by immutable DVM ID. Returns `undefined` when absent. */
export function getBuilderDvm(dvmId: string): BuilderDvmEntry | undefined {
  return loadBuilderStore().dvms[dvmId];
}

/**
 * Read a self-hosted DVM entry by its local handle. Platform DVM operations
 * must use {@link getBuilderDvm} with their resolved immutable ID instead.
 */
export function getSelfHostedBuilderDvm(handle: string): BuilderDvmEntry | undefined {
  return Object.values(loadBuilderStore().dvms).find(
    (entry) => entry.self_hosted && entry.handle === handle
  );
}

/**
 * Every entry recorded for `handle`, whichever way its canonical ID was
 * obtained. A DVM addressed by handle rather than through platform selection
 * `--endpoint`, or a machine holding no platform auth — has no other
 * selector, and how it was deployed does not change which lock keys it
 * derives. Returns more than one entry only when two share a
 * handle. Purely local callers refuse that ambiguity; an endpoint-aware lock
 * resolver may compare all candidates with the DVM's advertised pubkey
 * but still refuses a miss or tie.
 */
export function findBuilderDvmsByHandle(handle: string): BuilderDvmEntry[] {
  return Object.values(loadBuilderStore().dvms).filter((entry) => entry.handle === handle);
}

/**
 * The entry for a platform DVM already resolved to its immutable ID, or a
 * typed refusal. The by-ID twin of {@link requireBuilderDvmByHandle}.
 */
export function requireSelectedBuilderDvm(dvmId: string): BuilderDvmEntry {
  const entry = getBuilderDvm(dvmId);
  if (!entry) {
    throw new DvmError(
      "dvm_not_initialized",
      `No builder.json entry for selected DVM ${dvmId}.`,
      "Run `dvmctl deploy` first so this DVM's canonical_dvm_id is recorded."
    );
  }
  return entry;
}

/**
 * The one entry recorded for `handle`, or a typed refusal. Every command that
 * addresses a DVM directly rather than through platform selection starts its
 * identity lookup here. Endpoint-aware lock operations may refine this
 * ambiguity from `/v1/info`; local-only operations keep this refusal
 */
export function requireBuilderDvmByHandle(handle: string): BuilderDvmEntry {
  const matches = findBuilderDvmsByHandle(handle);
  if (matches.length > 1) {
    throw new DvmError(
      "ambiguous_dvm_handle",
      `${matches.length} builder.json entries claim the handle "${handle}".`,
      `Addressing a DVM by handle cannot choose between them, and either choice derives lock keys that open nothing. Candidates: ${matches
        .map((entry) => entry.canonical_dvm_id)
        .join(
          ", "
        )}. Select this DVM through the platform instead, or remove the entry you no longer operate from ${BUILDER_FILE}.`
    );
  }
  if (matches.length === 0) {
    throw new DvmError(
      "dvm_not_initialized",
      `No builder.json entry on this machine for "${handle}".`,
      `An entry is recorded by the deploy that created the DVM, so check the handle and that you are on the machine that deployed it. For a DVM you host yourself and have never initialized here, \`dvmctl init ${handle} --self-hosted\` records one — but never run that against a DVM already holding proofs: it mints a fresh canonical_dvm_id, and every proof locked under the old one becomes underivable.`
    );
  }
  return matches[0];
}

/**
 * Write a DVM entry, creating `~/.dvmkit/` if needed. The immutable DVM ID is
 * both the record key and the canonical BIP-32 derivation input, so same-slug
 * DVMs retain independent lock and payout state. Mode 0600 on the file keeps
 * the mapping from being casually enumerable through the filesystem.
 * Replaces the entry fully — for partial updates use `patchBuilderDvm`.
 */
export function upsertBuilderDvm(dvmId: string, entry: Omit<BuilderDvmEntry, "updated_at">): void {
  if (entry.canonical_dvm_id !== dvmId) {
    throw new Error(
      `Builder-store key ${dvmId} does not match canonical_dvm_id ${entry.canonical_dvm_id}`
    );
  }
  mkdirSync(BUILDER_CONFIG_DIR, { recursive: true, mode: 0o700 });
  const store = loadBuilderStore();
  store.dvms[dvmId] = { ...entry, updated_at: new Date().toISOString() };
  writeBuilderStore(store);
}

/**
 * Merge `patch` into the existing entry for `dvmId`, preserving fields the
 * caller doesn't touch. Throws when no entry exists — partial updates only
 * make sense once `dvmctl deploy` / `dvmctl init` has seeded
 * `canonical_dvm_id` + `current_rotation_index`. Used by `dvmctl set-payout`.
 */
export function patchBuilderDvm(
  dvmId: string,
  patch: Partial<Omit<BuilderDvmEntry, "updated_at">>
): BuilderDvmEntry {
  mkdirSync(BUILDER_CONFIG_DIR, { recursive: true, mode: 0o700 });
  const store = loadBuilderStore();
  if (!Object.prototype.hasOwnProperty.call(store.dvms, dvmId)) {
    throw new Error(
      `Cannot patch DVM ${dvmId}: no entry exists in ${BUILDER_FILE}. Run \`dvmctl deploy\` or \`dvmctl init --self-hosted\` first.`
    );
  }
  const existing = store.dvms[dvmId];
  const next: BuilderDvmEntry = {
    ...existing,
    ...patch,
    updated_at: new Date().toISOString(),
  };
  store.dvms[dvmId] = next;
  writeBuilderStore(store);
  return next;
}

function writeBuilderStore(store: BuilderStore): void {
  const content = JSON.stringify(store, null, 2) + "\n";
  backupSecretFile(BUILDER_FILE, content);

  const tmp = `${BUILDER_FILE}.tmp`;
  try {
    writeFileSync(tmp, content, { mode: 0o600 });
    renameSync(tmp, BUILDER_FILE);
  } catch (err) {
    try {
      unlinkSync(tmp);
    } catch {
      // best-effort cleanup; a leftover tmp never replaces the live store
    }
    throw err;
  }

  // Re-tighten after rename: a stale tmp file may have carried wider mode.
  try {
    chmodSync(BUILDER_FILE, 0o600);
  } catch {
    // POSIX-only; no-op on Windows.
  }
}

/** Convert v1 slug-keyed records to the v2 immutable-ID record key. */
function migrateV1Store(parsed: Record<string, unknown>): BuilderStore {
  if (typeof parsed.dvms !== "object" || parsed.dvms === null) {
    throw new Error(`${BUILDER_FILE} is missing the dvms object`);
  }

  const dvms: Record<string, BuilderDvmEntry> = {};
  for (const [handle, rawEntry] of Object.entries(parsed.dvms)) {
    if (typeof rawEntry !== "object" || rawEntry === null) {
      throw new Error(`${BUILDER_FILE} has an invalid DVM entry for ${handle}`);
    }
    const entry = rawEntry as Omit<BuilderDvmEntry, "handle">;
    const dvmId = entry.canonical_dvm_id;
    if (typeof dvmId !== "string") {
      throw new Error(`${BUILDER_FILE} has no canonical_dvm_id for ${handle}`);
    }
    if (Object.prototype.hasOwnProperty.call(dvms, dvmId)) {
      throw new Error(`${BUILDER_FILE} has multiple entries for canonical_dvm_id ${dvmId}`);
    }
    dvms[dvmId] = { ...entry, handle };
  }

  return {
    version: CURRENT_VERSION,
    ...(typeof parsed.identity_pubkey === "string"
      ? { identity_pubkey: parsed.identity_pubkey }
      : {}),
    dvms,
  };
}
