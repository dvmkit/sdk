#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

import ts from "typescript";

import { hasValueExport, inspectDeclaration, publicEntryPoints, readStability } from "./api-surface.mjs";

const root = resolve(import.meta.dirname, "..");
const outputPath = join(root, "docs", "API.md");
const mode = process.argv[2];
if (mode !== "--check" && mode !== "--write") {
  fail("use --check or --write");
}

const manifest = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const sections = publicEntryPoints.map((entryPoint) => inspectEntry(entryPoint));
const generated = render(sections);

if (mode === "--write") {
  writeFileSync(outputPath, generated);
  console.log(`wrote ${relativeOutput()}`);
} else {
  let current;
  try {
    current = readFileSync(outputPath, "utf8");
  } catch {
    fail(`${relativeOutput()} is missing; run npm run docs:api after npm run build`);
  }
  if (current !== generated) {
    fail(`${relativeOutput()} is stale; run npm run docs:api after npm run build`);
  }
  const count = sections.reduce((sum, section) => sum + section.symbols.length, 0);
  console.log(`SDK API reference ok: ${count} public names across ${sections.length} entry points`);
}

/** @param {string} entryPoint */
function inspectEntry(entryPoint) {
  const target = manifest.exports?.[entryPoint];
  if (!target?.types) fail(`package.json is missing declarations for ${entryPoint}`);
  const { checker, symbols: exported } = inspectDeclaration(root, target.types);
  const levels = readStability(root, entryPoint);
  const symbols = exported.map((symbol) => {
    const stability = levels.get(symbol.getName());
    if (!stability) fail(`${entryPoint}:${symbol.getName()} is missing stability`);
    return { ...describeSymbol(symbol, checker), stability };
  });
  return { entryPoint, declaration: target.types, symbols };
}

/** @param {ts.Symbol} exported @param {ts.TypeChecker} checker */
function describeSymbol(exported, checker) {
  let symbol = exported;
  if (exported.flags & ts.SymbolFlags.Alias) {
    symbol = checker.getAliasedSymbol(exported);
  }
  const flags = symbol.flags;
  const kind =
    flags & ts.SymbolFlags.Class
      ? "class"
      : flags & ts.SymbolFlags.Interface
        ? "interface"
        : flags & ts.SymbolFlags.TypeAlias
          ? "type"
          : flags & ts.SymbolFlags.Function
            ? "function"
            : flags & ts.SymbolFlags.Enum
              ? "enum"
              : flags & ts.SymbolFlags.Variable
                ? "value"
                : "export";
  const documentation = cleanDocumentation(
    ts.displayPartsToString(exported.getDocumentationComment(checker)) ||
      ts.displayPartsToString(symbol.getDocumentationComment(checker))
  );
  return { name: exported.getName(), kind, availability: hasValueExport(exported, checker) ? "runtime" : "type-only", documentation };
}

/** @param {string} raw */
function cleanDocumentation(raw) {
  const cleaned = raw
    .replace(/\{@link\s+([^}\s]+)(?:\s+([^}]*\S))?\s*\}/gu, (_match, target, label) => label ?? target)
    .replace(/\s+/gu, " ")
    .replace(/\s+([.,;:!?])/gu, "$1")
    .trim();
  if (!cleaned) return "Exported declaration from the built public entry point.";
  const firstSentence = cleaned.match(/^.*?(?:[.!?](?=\s|$)|$)/u)?.[0] ?? cleaned;
  return firstSentence.replace(/\|/gu, "\\|");
}

/** @param {{ entryPoint: string, declaration: string, symbols: { name: string, kind: string, availability: string, documentation: string, stability: string }[] }[]} sections */
function render(sections) {
  const count = sections.reduce((sum, section) => sum + section.symbols.length, 0);
  const lines = [
    "# API reference",
    "",
    "<!-- Generated by scripts/generate-api-reference.mjs. Do not edit by hand. -->",
    "",
    `This reference is generated from the built TypeScript declarations and covers ${count} names across the three supported public entry points. Run \`npm run build && npm run docs:api\` to refresh it; \`npm run check:api\` rejects stale output.`,
    "",
    "Stability levels follow the [compatibility policy](PROTOCOL-NOTES.md#compatibility-and-versioning). Runtime exports are available as JavaScript values; type-only exports are available only to TypeScript.",
    "",
  ];

  for (const section of sections) {
    const specifier = `@dvmkit/sdk${section.entryPoint === "." ? "" : section.entryPoint.slice(1)}`;
    lines.push(`## \`${specifier}\``, "");
    lines.push(`${entryPointGuidance(section.entryPoint)} Generated from \`${section.declaration}\`.`, "");
    lines.push("| Name | Kind | Availability | Stability | Guidance |", "| --- | --- | --- | --- | --- |");
    for (const symbol of section.symbols) {
      lines.push(`| \`${symbol.name}\` | ${symbol.kind} | ${symbol.availability} | ${symbol.stability} | ${symbol.documentation} |`);
    }
    lines.push("");
  }
  lines.push(
    "## Durable waits",
    "",
    "Use `await ctx.sleep(id, durationMs, { hint })` or `await ctx.sleepUntil(id, at, { hint })` between polls. Give each sleep a unique ID within the job and reserve the `sleep:` step prefix for the SDK. The first execution caches the deadline. Pass finite milliseconds or a valid Date. A sleep cannot overlap another sleep, a prompt, or a payment ask. Cancellation rejects the wait with `JobCancelledError`.",
    "",
    "The job goes to `working`. Its working message includes `wake_at_ms` as epoch milliseconds. A stored sleeper refuses ordinary inbound messages with HTTP 409 and `job_sleeping`. Callers can still read the message stream, cancel, or send a standing decline where supported.",
    "",
    "Durability requires `PostgresJobStore`. Memory and custom stores without sleep persistence can wait in-process. For a container DVM on Fly, set `min_machines_running: 1` in `package.json#dvmkit` so a replacement Machine can adopt sleepers. The default watchdog adopts after roughly five minutes plus a sweep interval. Setting `processingWatchdog: 0` disables reaping and sleep adoption. Recovery covers time parked in a sleep. A restart while the handler is awake, such as during a poll, still fails the job.",
    "",
    "Replay runs `onJob` from the top with the **last persisted** `ctx.state`. Derive progress from loop indices and `ctx.step` results. Keep provider output, including text, artifacts, progress, and working messages, a deterministic function of the input and cached steps. The runtime suppresses repeated output by counting provider messages. A message conditional on an uncached outcome can shift that count and swallow new output. Paid asks and completed sleeps replay from history.",
    "",
    "The testing context resolves waits immediately and records `{ id, wake_at_ms }` in `ctx.sleeps`. Set `sleep: \"real\"` when creating the context to exercise timers.",
    "",
    "| Event | Outcome and charge |",
    "| --- | --- |",
    "| Worker stops while parked | A replacement resumes the saved wait. Charges stay the same. |",
    "| Worker stops while awake, or six adoptions fail to re-park | Job fails with `worker_died_mid_job`. Finished pieces are charged and the active piece is released. |",
    "| Handler throws or calls `ctx.fail` | Job fails. Finished pieces are charged and the active piece is released. |",
    "| Caller deletes the job | Job is cancelled. Finished pieces and the active piece are charged. |",
    "| Caller declines with a standing mandate | The current piece runs to its end. The next ask cancels the job and charges only finished pieces. |",
    "| Ask expires | Job is cancelled and finished pieces are charged. |",
    "| Handler calls `ctx.complete` | Job completes and every paid piece is charged. |",
    ""
  );
  return lines.join("\n");
}

/** @param {string} entryPoint */
function entryPointGuidance(entryPoint) {
  if (entryPoint === ".") return "Builder declarations, handler context, schemas, pricing, and safe request helpers.";
  if (entryPoint === "./server") return "Node server hosting, persistence, authentication, compatibility, and payment infrastructure.";
  return "Deterministic in-memory contexts and stores for testing handlers without a live server or payment rail.";
}

function relativeOutput() {
  return "docs/API.md";
}

/** @param {string} message @returns {never} */
function fail(message) {
  console.error(`api reference: ${message}`);
  process.exit(1);
}
