#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

import ts from "typescript";

const root = resolve(import.meta.dirname, "..");
const outputPath = join(root, "docs", "API.md");
const mode = process.argv[2];
if (mode !== "--check" && mode !== "--write") {
  fail("use --check or --write");
}

const manifest = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
const publicEntryPoints = [".", "./server", "./testing"];
const sections = publicEntryPoints.map((entryPoint) => inspectEntry(entryPoint));
const generated = render(sections);

if (mode === "--write") {
  writeFileSync(outputPath, generated);
  console.log(`wrote ${relativeOutput()}`);
} else {
  let current;
  try {
    current = readFileSync(outputPath, "utf8");
  } catch {
    fail(`${relativeOutput()} is missing; run npm run docs:api after npm run build`);
  }
  if (current !== generated) {
    fail(`${relativeOutput()} is stale; run npm run docs:api after npm run build`);
  }
  const count = sections.reduce((sum, section) => sum + section.symbols.length, 0);
  console.log(`SDK API reference ok: ${count} public names across ${sections.length} entry points`);
}

/** @param {string} entryPoint */
function inspectEntry(entryPoint) {
  const target = manifest.exports?.[entryPoint];
  if (!target?.types) fail(`package.json is missing declarations for ${entryPoint}`);
  const declarationPath = join(root, target.types);
  const program = ts.createProgram({
    rootNames: [declarationPath],
    options: {
      module: ts.ModuleKind.ESNext,
      moduleResolution: ts.ModuleResolutionKind.Bundler,
      skipLibCheck: true,
      target: ts.ScriptTarget.ES2024,
    },
  });
  const checker = program.getTypeChecker();
  const source = program.getSourceFile(declarationPath);
  const moduleSymbol = source && checker.getSymbolAtLocation(source);
  if (!moduleSymbol) fail(`could not inspect ${target.types}`);

  const symbols = checker
    .getExportsOfModule(moduleSymbol)
    .map((exported) => describeSymbol(exported, checker))
    .sort((left, right) => left.name.localeCompare(right.name));
  return { entryPoint, declaration: target.types, symbols };
}

/** @param {ts.Symbol} exported @param {ts.TypeChecker} checker */
function describeSymbol(exported, checker) {
  let symbol = exported;
  if (exported.flags & ts.SymbolFlags.Alias) {
    symbol = checker.getAliasedSymbol(exported);
  }
  const flags = symbol.flags;
  const kind =
    flags & ts.SymbolFlags.Class
      ? "class"
      : flags & ts.SymbolFlags.Interface
        ? "interface"
        : flags & ts.SymbolFlags.TypeAlias
          ? "type"
          : flags & ts.SymbolFlags.Function
            ? "function"
            : flags & ts.SymbolFlags.Enum
              ? "enum"
              : flags & ts.SymbolFlags.Variable
                ? "value"
                : "export";
  const documentation = cleanDocumentation(
    ts.displayPartsToString(exported.getDocumentationComment(checker)) ||
      ts.displayPartsToString(symbol.getDocumentationComment(checker))
  );
  return { name: exported.getName(), kind, documentation };
}

/** @param {string} raw */
function cleanDocumentation(raw) {
  const cleaned = raw
    .replace(/\{@link\s+([^}\s]+)(?:\s+([^}]*\S))?\s*\}/gu, (_match, target, label) => label ?? target)
    .replace(/\s+/gu, " ")
    .replace(/\s+([.,;:!?])/gu, "$1")
    .trim();
  if (!cleaned) return "Exported declaration from the built public entry point.";
  const firstSentence = cleaned.match(/^.*?(?:[.!?](?=\s|$)|$)/u)?.[0] ?? cleaned;
  return firstSentence.replace(/\|/gu, "\\|");
}

/** @param {{ entryPoint: string, declaration: string, symbols: { name: string, kind: string, documentation: string }[] }[]} sections */
function render(sections) {
  const count = sections.reduce((sum, section) => sum + section.symbols.length, 0);
  const lines = [
    "# API reference",
    "",
    "<!-- Generated by scripts/generate-api-reference.mjs. Do not edit by hand. -->",
    "",
    `This reference is generated from the built TypeScript declarations and covers ${count} names across the three supported public entry points. Run \`npm run build && npm run docs:api\` to refresh it; \`npm run check:api\` rejects stale output.`,
    "",
  ];

  for (const section of sections) {
    const specifier = `@dvmkit/sdk${section.entryPoint === "." ? "" : section.entryPoint.slice(1)}`;
    lines.push(`## \`${specifier}\``, "");
    lines.push(`${entryPointGuidance(section.entryPoint)} Generated from \`${section.declaration}\`.`, "");
    lines.push("| Name | Kind | Guidance |", "| --- | --- | --- |");
    for (const symbol of section.symbols) {
      lines.push(`| \`${symbol.name}\` | ${symbol.kind} | ${symbol.documentation} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

/** @param {string} entryPoint */
function entryPointGuidance(entryPoint) {
  if (entryPoint === ".") return "Builder declarations, handler context, schemas, pricing, and safe request helpers.";
  if (entryPoint === "./server") return "Node server hosting, persistence, authentication, compatibility, and payment infrastructure.";
  return "Deterministic in-memory contexts and stores for testing handlers without a live server or payment rail.";
}

function relativeOutput() {
  return "docs/API.md";
}

/** @param {string} message @returns {never} */
function fail(message) {
  console.error(`api reference: ${message}`);
  process.exit(1);
}
